import { test, expect } from './fixtures';
import type { APIRequestContext } from '@playwright/test';
import { container } from './container';
import { settleAfterApply } from './pipewire-conf';
import { CONFIG, cleanupPipeWire, readFile, sinkNode, standInPwDump, writeFile } from './pw-helpers';

// Which sink an audio output group member resolves to when the group is
// applied.  The member's cached nodeTarget (from the last apply) is only
// evidence about the card it was resolved for; these check it is not used for
// another card, or for a card FPP has since taken over.  The container has no
// sound card, so the graph comes from a stand-in pw-dump and FPP's ownership
// from a 95-fpp-alsa-sink.conf written for the test.

test.skip(!container, 'stubs pw-dump and reads the generated config inside the run-web.sh container');

test.afterEach(cleanupPipeWire);

async function apply(request: APIRequestContext, member: Record<string, unknown>) {
  writeFile(`${CONFIG}/pipewire-audio-groups.json`, {
    groups: [{ id: 1, name: 'Out', enabled: true, channels: 2, members: [{ channels: 2, ...member }] }],
  });
  const r = await request.post('/api/pipewire/audio/groups/apply', { timeout: 120_000 });
  expect(r.ok(), await r.text()).toBe(true);
  await settleAfterApply(request);
  return {
    conf: readFile(`${CONFIG}/pipewire-audio-groups.conf`),
    member: JSON.parse(readFile(`${CONFIG}/pipewire-audio-groups.json`)).groups[0].members[0],
  };
}

test("a member resolves to its own card's FPP adapter, not one cached for another card", async ({ request }) => {
  // Regression: 31905cf7f. A member moved to card X kept the nodeTarget
  // resolved for its old card; that adapter was still live, so the apply
  // accepted it and the group kept playing out of the old card.
  const dump = standInPwDump([sinkNode(40, 'fpp_alsa_other'), sinkNode(41, 'fpp_alsa_x')]);
  expect(dump, 'the stand-in pw-dump is not the one the API runs').toContain('fpp_alsa_x');
  const { conf, member } = await apply(request, { cardId: 'X', nodeTarget: 'fpp_alsa_other' });
  expect(member.nodeTarget).toBe('fpp_alsa_x');
  expect(conf).toContain('"fpp_alsa_x"');
  expect(conf, 'the group still targets the old card').not.toContain('fpp_alsa_other');
});

test('a WirePlumber name cached for a card FPP now owns is dropped', async ({ request }) => {
  // Regression: c1bb01ad3. Once fppinit takes a card over (listing it on the
  // "# cards:" line of 95-fpp-alsa-sink.conf), WirePlumber's alsa_output node
  // for it never exists again; a member that cached that name was still sent
  // there, as if the device were only unplugged, and played silence forever.
  writeFile('/etc/pipewire/pipewire.conf.d/95-fpp-alsa-sink.conf',
    '# Auto-generated by FPP\n# cards: x\ncontext.objects = [\n]\n');
  const cached = 'alsa_output.usb-fpp_tests_card-00.analog-stereo';
  const { conf } = await apply(request, { cardId: 'X', nodeTarget: cached });
  expect(conf, 'the group targets a node that cannot exist').not.toContain(cached);

  // The control: a card FPP does not own keeps its cached WirePlumber name.
  writeFile('/etc/pipewire/pipewire.conf.d/95-fpp-alsa-sink.conf',
    '# Auto-generated by FPP\n# cards: y\ncontext.objects = [\n]\n');
  const other = await apply(request, { cardId: 'X', nodeTarget: cached });
  expect(other.conf).toContain(cached);
});
